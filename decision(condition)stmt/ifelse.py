# Write a Python program to check whether an entered number is positive or negative
num = int(input("Enter a number: "))
if num > 0:
    print("Positive number")
else:
    print("Negative number")



# Write a Python program to check whether a student has passed or failed based on the entered mark.    
mark = int(input("Enter mark: "))
if mark >= 40:
    print("Passed")
else:
    print("Failed")